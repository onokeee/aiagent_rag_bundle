def main() -> int:
    total = 0
    for ws, label, site, v in SITES:
        folder = DOCS / ws
        folder.mkdir(parents=True, exist_ok=True)
        if ws.startswith("manual"):
            docs = build_manual(ws, label, site, v)
        elif ws.startswith("trouble"):
            docs = build_trouble(ws, label, site, v)
        else:
            docs = build_generic(ws, label, site, v)
        for name, text in docs.items():
            (folder / name).write_text(text.strip() + "\n", encoding="utf-8")
        total += len(docs)
        print(f"  {ws:20s} {label:26s} {len(docs)}件")
    print(f"\n  合計 {total} 文書 / {len(SITES)} KB を作成")
    return 0


